function cleanText(text){
  var t=text;
  if(exact[t])t=exact[t];
  for(var i=0;i<replaces.length;i++)t=t.replace(replaces[i][0],replaces[i][1]);
  return t;
}

function walk(root){
  if(!root)return;
  var walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
  var node,items=[];
  while((node=walker.nextNode()))items.push(node);
  items.forEach(function(n){
    var before=n.nodeValue;
    var after=cleanText(before);
    if(after!==before)n.nodeValue=after;
  });
}

