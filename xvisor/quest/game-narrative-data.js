export function getEncounterCopy(active, state = {}) {
  const copy = ENCOUNTER_COPY[active?.key];
  if (!copy) return null;
  const people = [...(state.prospects || []), ...(state.customers || []), ...(state.team || [])];
  const target = people.find(person => person.id === active.targetId);
  const byId = new Map(copy.choices.map(choice => [choice.id, choice]));
  byId.set("skip", { id: "skip", label: "ไว้ก่อน กลับไปดูแลงาน", detail: "ข้ามได้ ไม่ใช้พลังงาน", result: "" });
  const choices = (active.choices || []).filter(choice => choice.id !== "skip");
  choices.push((active.choices || []).find(choice => choice.id === "skip") || { id: "skip", effectKey: `${active.key}:skip` });
  return {
    key: active.id || active.key, title: copy.title,
    speaker: copy.speaker, portrait: copy.portrait, mood: copy.mood || "warm",
    line: `${target?.name ? `เรื่องของ${target.name} · ` : ""}${selectNarrativeText(state, active.key, copy.lines)}`,
    tip: copy.tips ? selectNarrativeText(state, `${active.key}:tip`, copy.tips) : "",
    targetName: target?.name || "",
    choices: choices.map(choice => byId.has(choice.id) ? { ...choice, ...byId.get(choice.id) } : null).filter(Boolean)
  };
}
