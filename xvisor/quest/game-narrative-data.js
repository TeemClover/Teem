// to the engine; viewing a story never advances its random-number generator.
export function narrativeSeed(state = {}) {
  return String(state.encounters?.seed ?? state.storySeed ?? state.runSeed ?? state.runId ?? "xvisor");
}

function hash(value) {
  let result = 2166136261;
  for (const character of String(value)) result = Math.imul(result ^ character.codePointAt(0), 16777619) >>> 0;
  return result;
}

export function selectNarrativeText(state, key, lines, position = null) {
  if (!lines.length) return "";
  const seed = `${narrativeSeed(state)}:${key}`;
  if (position === null) return lines[hash(seed) % lines.length];
  const order = lines.map((line, index) => ({ line, index, order: hash(`${seed}:${index}`) }))
    .sort((a, b) => a.order - b.order || a.index - b.index);
  return order[Math.max(0, Math.floor(Number(position) || 0)) % order.length].line;
}

