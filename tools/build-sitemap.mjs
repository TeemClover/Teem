#!/usr/bin/env node
/**
 * sitemap.xml for the restructured site (BLUEPRINT v3.0 §10).
 *
 *   node tools/build-sitemap.mjs          write sitemap.xml
 *   node tools/build-sitemap.mjs --check  exit 1 if sitemap.xml differs
 *
 * Only the pages listed below go in. Each one must exist, must not be noindex (meta or a
 * vercel.json X-Robots-Tag rule), and its canonical (when present) must point to itself.
 * lastmod = the date the page file last changed in Git (today for uncommitted changes).
 * Everything §2 cuts or archives (affiliate, brand/client, old doors, /home/) stays out.
 */
import {readFile, writeFile, stat, readdir} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://www.myclover.com';

const work = JSON.parse(await readFile(path.join(ROOT, 'work/cases.json'), 'utf8')).cases.map(c => `/work/${c.slug}/`);
// every published recipe page (ako/kitchen/<slug>/index.html, built by npm run build:ako)
const recipes = [];
for (const e of await readdir(path.join(ROOT, 'ako/kitchen'), {withFileTypes: true})) {
  if (e.isDirectory() && /^[a-z0-9-]+$/.test(e.name)) {
    try { await stat(path.join(ROOT, 'ako/kitchen', e.name, 'index.html')); recipes.push(`/ako/kitchen/${e.name}/`); } catch {}
  }
}
export const SITEMAP_PATHS = [
  '/', '/work/', ...work, '/hire/', '/walkthrough/',
  '/classroom/', '/classroom/lesson-0.html', '/classroom/free-ai.html', '/classroom/image-ai.html', '/classroom/clip-ai.html',
  '/classroom/notebooklm.html', '/classroom/prompts.html', '/classroom/season-commands.html', '/classroom/season-video.html',
  '/classroom/season-agent.html', '/classroom/first-web.html', '/classroom/sauce-cup/', '/classroom/dungeon/',
  '/tour/', '/resume/', '/meet/', '/courses/',
  '/core7/', '/forge/', '/book/ai-sauce/', '/en/',
  '/ako/kitchen/', ...recipes.sort(),
];

const fileFor = p => path.join(ROOT, p.endsWith('/') ? p + 'index.html' : p);
const isoDate = d => d.toISOString().slice(0, 10);

function lastmod(file) {
  const rel = path.relative(ROOT, file);
  try {
    const dirty = execFileSync('git', ['status', '--porcelain', '--', rel], {cwd: ROOT, encoding: 'utf8'}).trim();
    if (dirty) return isoDate(new Date());
    const day = execFileSync('git', ['log', '-1', '--format=%cs', '--', rel], {cwd: ROOT, encoding: 'utf8'}).trim();
    return day || isoDate(new Date());
  } catch { return isoDate(new Date()); }
}

function headerNoindex(vercel, p) {
  return vercel.headers.some(rule => {
    if (rule.has || !rule.headers.some(h => /x-robots-tag/i.test(h.key) && /noindex/i.test(h.value))) return false;
    const re = new RegExp('^' + rule.source.replace(/:path\*/g, '.*').replace(/:[a-z]+/gi, '[^/]+') + '$');
    return re.test(p) || re.test(p.replace(/\/$/, ''));
  });
}

export async function buildSitemap() {
  const vercel = JSON.parse(await readFile(path.join(ROOT, 'vercel.json'), 'utf8'));
  const problems = [], rows = [];
  for (const p of SITEMAP_PATHS) {
    const file = fileFor(p);
    let html;
    try { await stat(file); html = await readFile(file, 'utf8'); } catch { problems.push(`${p}: no file`); continue; }
    const robots = html.match(/<meta name="robots" content="([^"]+)"/i)?.[1] || '';
    if (/noindex/i.test(robots)) problems.push(`${p}: meta robots ${robots}`);
    if (headerNoindex(vercel, p)) problems.push(`${p}: vercel.json X-Robots-Tag noindex`);
    const canonical = html.match(/<link rel="canonical" href="([^"]+)"/i)?.[1];
    if (canonical && canonical !== SITE + p) problems.push(`${p}: canonical ${canonical}`);
    rows.push(`  <url><loc>${SITE}${p}</loc><lastmod>${lastmod(file)}</lastmod></url>`);
  }
  if (problems.length) throw Error('sitemap refuses:\n' + problems.join('\n'));
  return `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by tools/build-sitemap.mjs (BLUEPRINT v3.0 §10). Edit the list there, not this file. -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${rows.join('\n')}\n</urlset>\n`;
}

if (path.resolve(process.argv[1] || '') === fileURLToPath(import.meta.url)) {
  const xml = await buildSitemap();
  const now = await readFile(path.join(ROOT, 'sitemap.xml'), 'utf8').catch(() => '');
  const strip = s => s.replace(/<lastmod>[^<]*<\/lastmod>/g, '');
  if (process.argv.includes('--check')) {
    if (strip(now) !== strip(xml)) { console.error('sitemap.xml is stale: run node tools/build-sitemap.mjs'); process.exit(1); }
    console.log(`sitemap.xml lists ${SITEMAP_PATHS.length} URLs`);
  } else {
    await writeFile(path.join(ROOT, 'sitemap.xml'), xml);
    console.log(`sitemap.xml: ${SITEMAP_PATHS.length} URLs`);
  }
}
