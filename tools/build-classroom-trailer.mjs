// Bundle the classroom trailer sources into one public script.
// Usage: node tools/build-classroom-trailer.mjs [--check]
import {readFile, writeFile, readdir} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const src = path.join(root, 'tools/classroom-trailer');
const out = path.join(root, 'assets/classroom-trailer.js');
const scenes = (await readdir(path.join(src, 'scenes'))).filter(f => f.endsWith('.js')).sort();
const parts = ['engine.js', 'meta.js', 'hud.js', 'score.js', ...scenes.map(f => 'scenes/' + f), 'boot.js'];
let bundle = '/* Generated by tools/build-classroom-trailer.mjs from tools/classroom-trailer/ — do not edit. */\n';
for (const part of parts) {
  let code;
  try { code = await readFile(path.join(src, part), 'utf8'); } catch { if (part === 'boot.js' || part === 'meta.js' || part === 'score.js') continue; throw new Error('Missing ' + part); }
  bundle += `\n/* ── ${part} ── */\n${code.trim()}\n`;
}
if (process.argv.includes('--check')) {
  const current = await readFile(out, 'utf8').catch(() => '');
  if (current !== bundle) { console.error('assets/classroom-trailer.js is stale; run node tools/build-classroom-trailer.mjs'); process.exit(1); }
  console.log('classroom trailer bundle is current');
} else {
  await writeFile(out, bundle);
  console.log(`Wrote assets/classroom-trailer.js (${parts.length} parts, ${(bundle.length / 1024).toFixed(1)} KB)`);
}
