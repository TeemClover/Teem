/** ที่นั่งของคนตั้งห้อง — ฝั่งที่เข้ามาทีหลังคือ 'b' */
export const HOST_SEAT = 'a';

/**
 * @param {boolean|null} seenBefore  รอบก่อนมีคู่แข่งอยู่ไหม (null = ยังไม่เคยเห็นสถานะห้อง)
 * @param {boolean} hasOpponent      รอบนี้มีคู่แข่งอยู่ไหม
 * @param {string} seat              ที่นั่งของเรา
 */
export function shouldWelcome(seenBefore, hasOpponent, seat) {
  return seenBefore === false && hasOpponent === true && seat === HOST_SEAT;
}
